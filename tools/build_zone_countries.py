#!/usr/bin/env python3
"""Writes lib/support/zone_countries.dart: the country of every IANA time
zone, from the system's zone.tab, so the app can tell from the phone's own
time zone (set automatically from where it is) which country it's in.

    python3 tools/build_zone_countries.py

Run it again when time zones change (rarely). The website's price finder
uses the same table (yournotalone-web/tools/build_prices.py).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ZONES = Path('/usr/share/zoneinfo/zone.tab')
OUT = ROOT / 'lib/support/zone_countries.dart'

zones = {}
for line in ZONES.read_text().splitlines():
    if line.startswith('#') or not line.strip():
        continue
    code, _, zone = line.split('\t')[:3]
    zones[zone] = code
# Older names some phones still report.
for old, new in {
    'Asia/Calcutta': 'Asia/Kolkata', 'Asia/Saigon': 'Asia/Ho_Chi_Minh',
    'Asia/Katmandu': 'Asia/Kathmandu', 'Asia/Rangoon': 'Asia/Yangon',
    'Asia/Dacca': 'Asia/Dhaka', 'Europe/Kiev': 'Europe/Kyiv',
    'Africa/Asmera': 'Africa/Asmara',
    'America/Buenos_Aires': 'America/Argentina/Buenos_Aires',
    'Atlantic/Faeroe': 'Atlantic/Faroe', 'Asia/Ulan_Bator': 'Asia/Ulaanbaatar',
    'US/Eastern': 'America/New_York', 'US/Central': 'America/Chicago',
    'US/Mountain': 'America/Denver', 'US/Pacific': 'America/Los_Angeles',
    'Europe/Belfast': 'Europe/London', 'GB': 'Europe/London',
    'Asia/Istanbul': 'Europe/Istanbul', 'America/Montreal': 'America/Toronto',
}.items():
    if new in zones:
        zones[old] = zones[new]

lines = [
    '// Generated by tools/build_zone_countries.py from zone.tab. Don\'t edit by hand.',
    '',
    '/// The country of each IANA time zone ("Africa/Nairobi" → "KE").',
    'const zoneCountries = <String, String>{',
]
lines += [f"  '{zone}': '{code}'," for zone, code in sorted(zones.items())]
lines += ['};', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print(f'{OUT.relative_to(ROOT)}: {len(zones)} time zones')
