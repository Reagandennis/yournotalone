/// What a country is called on screen: its name on the crisis screen in
/// this build if it has one there (some are in the country's own language,
/// "Deutschland"), else its English name, else the code itself.
String countryName(String code, {bool? drafts}) {
  final upper = code.toUpperCase();
  for (final region in availableCrisisRegions(drafts: drafts)) {
    if (region.code == upper) return region.label;
  }
  return isoCountries[upper] ?? upper;
}

/// One entry in a list of countries to choose from.
typedef CountryChoice = ({String code, String name});

/// Every country in [isoCountries], named by [countryName] and sorted by
/// that name, letters with accents beside the plain ones.
List<CountryChoice> countryChoices({bool? drafts}) {
  final labels = {
    for (final region in availableCrisisRegions(drafts: drafts))
      region.code: region.label,
  };
  return [
    for (final MapEntry(key: code, value: name) in isoCountries.entries)
      (code: code, name: labels[code] ?? name),
  ]..sort((a, b) => foldForSearch(a.name).compareTo(foldForSearch(b.name)));
}

/// Whether [choice] answers what someone typed: its name on screen, its
/// English name or its code, ignoring case and accents.
bool countryMatches(CountryChoice choice, String query) {
  final q = foldForSearch(query.trim());
  if (q.isEmpty) return true;
  return foldForSearch(choice.name).contains(q) ||
      foldForSearch(isoCountries[choice.code] ?? '').contains(q) ||
      choice.code.toLowerCase() == q;
}

const _accents = {
  'à': 'a', 'á': 'a', 'â': 'a', 'ã': 'a', 'ä': 'a', 'å': 'a', //
  'ç': 'c',
  'è': 'e', 'é': 'e', 'ê': 'e', 'ë': 'e',
  'ì': 'i', 'í': 'i', 'î': 'i', 'ï': 'i',
  'ñ': 'n',
  'ò': 'o', 'ó': 'o', 'ô': 'o', 'õ': 'o', 'ö': 'o',
  'ù': 'u', 'ú': 'u', 'û': 'u', 'ü': 'u',
  'ý': 'y',
  '’': "'",
};

/// Lower case, without the accents above, for sorting and searching.
String foldForSearch(String text) {
  final buffer = StringBuffer();
  for (final char in text.toLowerCase().split('')) {
    buffer.write(_accents[char] ?? char);
  }
  return buffer.toString();
}
